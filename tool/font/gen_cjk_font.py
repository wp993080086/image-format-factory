"""生成中文 BMFont 点阵字体，供 image 包 BitmapFont.fromZip 使用。

字体来源：C:/Windows/Fonts/Noto Sans SC (TrueType).otf（SIL OFL 1.1，可随包分发）。
字库：ASCII 可打印字符 + 现代汉语常用字 3500 + 常用标点/符号。
输出：lib/core/image/fonts/cjk_<size>.dart，内嵌 BMFont zip 字节常量。

生成物是白色字形 + alpha 的点阵，运行时由 drawString 的 color filter 染成任意颜色。
"""

import os
import io
import base64
import zipfile
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = r"C:\Windows\Fonts\Noto Sans SC (TrueType).otf"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_DIR = os.path.join(ROOT, "lib", "core", "image", "fonts")
SIZES = [24]  # 仅一档基准点阵，其他字号运行时缩放字形 image
PADDING = 1          # 字形之间的间距（像素）
SHEET_MAX = 1024     # 图集单行最大宽度，控制单张 PNG 尺寸

# ASCII 可打印字符
chars = [chr(c) for c in range(0x20, 0x7F)]

# 常用汉字：GB2312 一级字库 3755 字（0xB0-0xD7，即 16-55 区，按拼音排序的高频字）
gb_cjk = []
for lead in range(0xB0, 0xD8):
    for trail in range(0xA1, 0xFF):
        b = bytes([lead, trail])
        try:
            ch = b.decode("gb2312")
            if "\u4e00" <= ch <= "\u9fff":
                gb_cjk.append(ch)
        except UnicodeDecodeError:
            pass
seen = set()
common_cjk = "".join(c for c in gb_cjk if not (c in seen or seen.add(c)))

# 常用标点 / 符号 / 全角
punct = "，。！？；：、“”‘’（）《》〈〉【】…—·￥％＃＆＊＋－／＝＠～｜·〇"
chars += [c for c in punct]
chars += [c for c in common_cjk]
# 去重并保持顺序
seen = set()
chars = [c for c in chars if not (c in seen or seen.add(c))]


def glyph_metrics(font, ch, size):
    bbox = font.getbbox(ch)  # (x0,y0,x1,y1) relative to origin at (0,0)
    # 以 baseline 为基准：xoffset=bbox.x0, yoffset=bbox.y0
    w = max(1, bbox[2] - bbox[0])
    h = max(1, bbox[3] - bbox[1])
    adv = round(font.getlength(ch))
    return bbox[0], bbox[1], w, h, max(w, adv)


def build(size):
    font = ImageFont.truetype(FONT_PATH, size)
    metrics = {}
    for ch in chars:
        metrics[ord(ch)] = glyph_metrics(font, ch, size)

    # 排版到图集：贪心装箱（按行，宽度上限 SHEET_MAX）
    placements = {}
    cell_w = {}
    cell_h = {}
    cx = cy = 0
    row_h = 0
    for code in metrics:
        xoff, yoff, w, h, adv = metrics[code]
        cw = w + PADDING * 2
        chh = h + PADDING * 2
        cell_w[code] = cw
        cell_h[code] = chh
        if cx + cw > SHEET_MAX:
            cx = 0
            cy += row_h
            row_h = 0
        placements[code] = (cx + PADDING, cy + PADDING)
        cx += cw
        row_h = max(row_h, chh)
    sheet_w = SHEET_MAX
    sheet_h = cy + row_h

    # 绘制图集（RGBA，白色字形 + alpha）
    sheet = Image.new("RGBA", (sheet_w, sheet_h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(sheet)
    for code in metrics:
        ch = chr(code)
        xoff, yoff, w, h, adv = metrics[code]
        px, py = placements[code]
        draw.text((px - xoff, py - yoff), ch, font=font, fill=(255, 255, 255, 255))

    buf = io.BytesIO()
    sheet.save(buf, format="PNG", optimize=True)
    png_bytes = buf.getvalue()

    # BMFont 文本定义（遵循 image 包解析的 attr 名）
    line_height = size + 4
    base = size
    lines = [
        "info face=\"CJK\" size=%d bold=0 italic=0 charset=\"\" unicode=1 stretchH=100 smooth=1 aa=1 padding=0,0,0,0 spacing=1,1" % size,
        "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0" % (line_height, base, sheet_w, sheet_h),
        "page id=0 file=\"cjk.png\"",
        "chars count=%d" % len(metrics),
    ]
    for code in metrics:
        xoff, yoff, w, h, adv = metrics[code]
        px, py = placements[code]
        lines.append(
            "char id=%d x=%d y=%d width=%d height=%d xoffset=%d yoffset=%d xadvance=%d page=0 chnl=0"
            % (code, px, py, w, h, xoff, yoff, adv)
        )
    fnt_bytes = ("\n".join(lines) + "\n").encode("utf-8")

    zbuf = io.BytesIO()
    with zipfile.ZipFile(zbuf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        z.writestr("cjk.fnt", fnt_bytes)
        z.writestr("cjk.png", png_bytes)
    zip_bytes = zbuf.getvalue()

    # 生成 Dart 文件：zip 字节以 base64 常量字符串内嵌（比十进制数组省约 3 倍体积）
    os.makedirs(OUT_DIR, exist_ok=True)
    out = os.path.join(OUT_DIR, "cjk_%d.dart" % size)
    b64 = base64.b64encode(zip_bytes).decode("ascii")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tool/font/gen_cjk_font.py — DO NOT EDIT\n")
        f.write("// 字形来源：Noto Sans SC (SIL OFL 1.1)，详见 assets/licenses/\n")
        f.write("import 'dart:convert';\n")
        f.write("import 'package:image/image.dart' as img;\n\n")
        f.write("/// %dpx 中文字体（BMFont zip base64），含 ASCII + 常用汉字 %d 个。\n" % (size, len(chars)))
        f.write("/// 仅构造一次；字号差异由 cjkFontFor(size) 缩放字形实现。\n")
        f.write("final img.BitmapFont cjk%d = img.BitmapFont.fromZip(base64Decode(_cjk%dB64));\n\n" % (size, size))
        f.write("const String _cjk%dB64 =\n" % size)
        # base64 每行 120 字符，Dart 相邻字符串字面量自动拼接
        for i in range(0, len(b64), 120):
            line = b64[i:i+120]
            f.write("  '%s'\n" % line)
        f.write("  ;\n")
    print("size=%d chars=%d sheet=%dx%d zip=%dKB b64=%dKB -> %s" % (
        size, len(chars), sheet_w, sheet_h, len(zip_bytes)//1024, len(b64)//1024, os.path.basename(out)))


if __name__ == "__main__":
    for s in SIZES:
        build(s)
